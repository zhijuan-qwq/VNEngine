// 资源落位脚本：把 ~/桌面/res 的素材复制进 public/ 并按需重命名，
// 同时生成 src/game/manifest.gen.ts（资产清单）。
// 用法：node scripts/setup-assets.mjs [资源目录]
import { mkdir, copyFile, readdir, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const resDir = process.argv[2] ?? path.join(os.homedir(), '桌面', 'res');
const projectRoot = path.resolve(import.meta.dirname, '..');
const publicDir = path.join(projectRoot, 'public');
const bgSrc = path.join(resDir, 'bg');
const charSrc = path.join(resDir, 'xingmi');
const bgmSrc = path.join(resDir, 'bgm');

const POSE_MAP = { front1: 'f1', front2: 'f2', side1: 's1' };
const SPRITE_RE =
  /^xingmi_clothes(\d)_(front\d|side1)_face_([a-z_]+?)_xingmi_clothes\d_(front\d|side1)_skin_([a-z]+)\.png$/;

// ---- 背景：重命名为 <id>.webp（去掉源文件的 bg_ 前缀），id 与文件名一致 ----
const images = {};
{
  const destBase = path.join(publicDir, 'bg');
  for (const category of await readdir(bgSrc, { withFileTypes: true })) {
    if (!category.isDirectory()) continue;
    await mkdir(path.join(destBase, category.name), { recursive: true });
    for (const file of await readdir(path.join(bgSrc, category.name))) {
      const stem = path.basename(file, path.extname(file));
      const id = stem.replace(/^bg_/, '');
      images[id] = `/bg/${category.name}/${id}${path.extname(file)}`;
      await copyFile(
        path.join(bgSrc, category.name, file),
        path.join(destBase, category.name, `${id}${path.extname(file)}`),
      );
    }
  }
  console.log(`bg: ${Object.keys(images).length} images`);
}

// ---- 立绘：重命名为 xingmi_<c1|c2>_<f1|f2|s1>_<face>_<skin>.png ----
let spriteCount = 0;
{
  const destDir = path.join(publicDir, 'char', 'xingmi');
  await mkdir(destDir, { recursive: true });
  for (const clothesDir of await readdir(charSrc, { withFileTypes: true })) {
    if (!clothesDir.isDirectory()) continue;
    for (const poseDir of await readdir(path.join(charSrc, clothesDir.name), {
      withFileTypes: true,
    })) {
      if (!poseDir.isDirectory()) continue;
      for (const file of await readdir(
        path.join(charSrc, clothesDir.name, poseDir.name),
      )) {
        const match = SPRITE_RE.exec(file);
        if (!match) throw new Error(`Unrecognized sprite filename: ${file}`);
        // 捕获组：1 clothes, 2 pose, 3 face, 4 尾部 pose（冗余）, 5 skin
        const [, clothes, pose, face, , skin] = match;
        const id = `xingmi_c${clothes}_${POSE_MAP[pose]}_${face}_${skin}`;
        if (images[id]) throw new Error(`Duplicate sprite id: ${id}`);
        images[id] = `/char/xingmi/${id}.png`;
        await copyFile(
          path.join(charSrc, clothesDir.name, poseDir.name, file),
          path.join(destDir, `${id}.png`),
        );
        spriteCount += 1;
      }
    }
  }
  console.log(`sprites: ${spriteCount} images`);
}

// ---- BGM：public/bgm/<file>，id 取文件名去扩展名 ----
const audio = {};
{
  const destDir = path.join(publicDir, 'bgm');
  await mkdir(destDir, { recursive: true });
  for (const file of await readdir(bgmSrc)) {
    const id = path.basename(file, path.extname(file));
    if (audio[id]) throw new Error(`Duplicate audio id: ${id}`);
    audio[id] = `/bgm/${file}`;
    await copyFile(path.join(bgmSrc, file), path.join(destDir, file));
  }
  console.log(`bgm: ${Object.keys(audio).length} tracks`);
}

// ---- 资产清单 ----
const gameDir = path.join(projectRoot, 'src', 'game');
await mkdir(gameDir, { recursive: true });
const manifest = `// Auto-generated by scripts/setup-assets.mjs — do not edit.
import type { AssetManifest } from '@/types/engine';

export const gameManifest: AssetManifest = {
  images: ${JSON.stringify(images, null, 2)},
  audio: ${JSON.stringify(audio, null, 2)},
  scripts: { game: '/script/game.vns' },
  spritesheets: {},
};
`;
await writeFile(
  path.join(projectRoot, 'src', 'game', 'manifest.gen.ts'),
  manifest,
);
console.log(
  `manifest: src/game/manifest.gen.ts (${Object.keys(images).length} images, ${Object.keys(audio).length} audio)`,
);
